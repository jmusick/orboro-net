  'A bookmarked collection of Path of Exile 2 sites and tools, filterable by tag, from build planners and crafting simulators to loot filters and trade sites.

{{bookmarks tag="poe2" exclude_categories="arpg,gaming"}}',
  'page',
  'published',
  (SELECT id FROM users WHERE role = 'admin' ORDER BY created_at ASC LIMIT 1),
  CAST(strftime('%s', 'now') AS INTEGER) * 1000,
  CAST(strftime('%s', 'now') AS INTEGER) * 1000,
  CAST(strftime('%s', 'now') AS INTEGER) * 1000,
